const DICTS: Record<Lang, AdminDict> = { fr, en, ar };

/** Locale BCP-47 pour le formatage des dates/nombres (Intl) selon la langue admin. */
const LOCALES: Record<Lang, string> = { fr: 'fr-FR', en: 'en-GB', ar: 'ar-DZ' };

type AdminLangContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  dir: 'ltr' | 'rtl';
  locale: string;
  t: AdminDict;
};

const AdminLangContext = createContext<AdminLangContextValue | null>(null);

function readStoredLang(): Lang {
  if (typeof window === 'undefined') return DEFAULT_LANG;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored && isLang(stored) ? stored : DEFAULT_LANG;
}

export function AdminLangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);
  const dir = LANG_META[lang].dir;

  useEffect(() => {
    const root = document.documentElement;
    root.lang = LANG_META[lang].htmlLang;
    root.dir = dir;
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang, dir]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);

  const value = useMemo<AdminLangContextValue>(
    () => ({ lang, setLang, dir, locale: LOCALES[lang], t: DICTS[lang] }),
    [lang, setLang, dir],
  );

  return <AdminLangContext value={value}>{children}</AdminLangContext>;
}

export function useAdminT(): AdminLangContextValue {
  const ctx = use(AdminLangContext);
  if (!ctx) throw new Error('useAdminT must be used inside <AdminLangProvider>');
  return ctx;
}
